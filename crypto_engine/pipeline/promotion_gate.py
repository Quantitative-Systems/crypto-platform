"""Crypto Engine — Automated Research-to-Production Promotion Gate.

Guarantees that ONLY filter-passed, institutionally verified strategies enter
the production `crypto_engine/`.

Evaluation Pipeline:
1. Evaluates candidate metrics generated by backtests or shadow validation.
2. Applies strict Institutional Quality Gates:
   - Profit Factor >= 1.25
   - Net Realized Alpha >= +10.0R
   - Minimum Sample Size >= 25 trades
   - Max Drawdown <= 30.0R
   - Win Rate >= 25.0% (with >= 4.0R target geometry)
3. Action:
   - IF PASSED -> Promoted to `crypto_engine/registry/champions.json` and archived in `research/candidates/passed/`.
   - IF FAILED -> Quarantined in `research/candidates/failed/` with explicit forensic failure reasons.
"""
from __future__ import annotations

import json
import logging
import os
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional

WORKSPACE_ROOT = Path(__file__).resolve().parent.parent.parent

PASSED_DIR = WORKSPACE_ROOT / "research" / "candidates" / "passed"
FAILED_DIR = WORKSPACE_ROOT / "research" / "candidates" / "failed"
REGISTRY_FILE = Path(__file__).resolve().parent.parent / "registry" / "champions.json"

PASSED_DIR.mkdir(parents=True, exist_ok=True)
FAILED_DIR.mkdir(parents=True, exist_ok=True)
REGISTRY_FILE.parent.mkdir(parents=True, exist_ok=True)

logger = logging.getLogger("PromotionGate")


class PromotionStatus(str, Enum):
    PASSED = "PASSED_PRODUCTION_CERTIFIED"
    FAILED = "FAILED_RESEARCH_QUARANTINED"


@dataclass
class PromotionVerdict:
    model_id: str
    symbol: str
    timeframe_set: str
    status: PromotionStatus
    profit_factor: float
    net_r: float
    total_trades: int
    win_rate_pct: float
    max_drawdown_r: float
    reasons: List[str]
    evaluated_at_utc: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "model_id": self.model_id,
            "symbol": self.symbol,
            "timeframe_set": self.timeframe_set,
            "status": self.status.value,
            "profit_factor": round(self.profit_factor, 3),
            "net_r": round(self.net_r, 2),
            "total_trades": self.total_trades,
            "win_rate_pct": round(self.win_rate_pct, 2),
            "max_drawdown_r": round(self.max_drawdown_r, 2),
            "reasons": self.reasons,
            "evaluated_at_utc": self.evaluated_at_utc,
        }


class ProductionPromotionGate:
    """Rigorous quantitative filter enforcing the No-Degradation Promotion Law."""

    MIN_PROFIT_FACTOR: float = 1.25
    MIN_NET_ALPHA_R: float = 10.0
    MIN_TOTAL_TRADES: int = 25
    MAX_ALLOWABLE_DRAWDOWN_R: float = 30.0
    MIN_WIN_RATE_PCT: float = 24.0

    @classmethod
    def evaluate_and_route(
        cls,
        model_id: str,
        symbol: str,
        timeframe_set: str,
        stream_metrics: Dict[str, Any],
        metadata: Optional[Dict[str, Any]] = None,
    ) -> PromotionVerdict:
        """Evaluates research results and routes candidate into passed or failed directories."""
        pf = float(stream_metrics.get("profit_factor", 0.0))
        net_r = float(stream_metrics.get("total_r", stream_metrics.get("net_r", 0.0)))
        n_trades = int(stream_metrics.get("total_trades", stream_metrics.get("trades", 0)))
        win_rate = float(stream_metrics.get("win_rate", 0.0))
        if win_rate <= 1.0 and win_rate > 0.0:
            win_rate *= 100.0  # Normalize to percentage
        max_dd = float(stream_metrics.get("max_drawdown_r", 0.0))

        reasons = []
        is_passed = True

        if n_trades < cls.MIN_TOTAL_TRADES:
            is_passed = False
            reasons.append(f"Insufficient trade sample: N={n_trades} < required {cls.MIN_TOTAL_TRADES}")

        if pf < cls.MIN_PROFIT_FACTOR:
            is_passed = False
            reasons.append(f"Profit factor {pf:.2f} below threshold {cls.MIN_PROFIT_FACTOR:.2f}")

        if net_r < cls.MIN_NET_ALPHA_R:
            is_passed = False
            reasons.append(f"Net alpha {net_r:+.2f}R below threshold +{cls.MIN_NET_ALPHA_R:.1f}R")

        if max_dd > cls.MAX_ALLOWABLE_DRAWDOWN_R:
            is_passed = False
            reasons.append(f"Max drawdown {max_dd:.1f}R exceeds allowable {cls.MAX_ALLOWABLE_DRAWDOWN_R:.1f}R")

        if win_rate < cls.MIN_WIN_RATE_PCT and n_trades > 0:
            is_passed = False
            reasons.append(f"Win rate {win_rate:.1f}% below minimum {cls.MIN_WIN_RATE_PCT:.1f}%")

        now_str = datetime.now(timezone.utc).isoformat()
        status = PromotionStatus.PASSED if is_passed else PromotionStatus.FAILED

        if is_passed:
            reasons.append("PASSED ALL GATES: Certified for live autonomous execution.")

        verdict = PromotionVerdict(
            model_id=model_id,
            symbol=symbol,
            timeframe_set=timeframe_set,
            status=status,
            profit_factor=pf,
            net_r=net_r,
            total_trades=n_trades,
            win_rate_pct=win_rate,
            max_drawdown_r=max_dd,
            reasons=reasons,
            evaluated_at_utc=now_str,
        )

        record_data = {
            **verdict.to_dict(),
            "metrics_snapshot": stream_metrics,
            "metadata": metadata or {},
        }

        if is_passed:
            # 1. Save artifact into research/candidates/passed/
            target_path = PASSED_DIR / f"{model_id}.json"
            with open(target_path, "w", encoding="utf-8") as f:
                json.dump(record_data, f, indent=2)

            # 2. Add or update champion in crypto_engine/registry/champions.json
            cls._register_champion(model_id, record_data)
            logger.info(">>> [PROMOTION APPROVED] %s passed all filters -> PROMOTED TO PRODUCTION CHAMPION!", model_id)

        else:
            # Save artifact into research/candidates/failed/
            target_path = FAILED_DIR / f"{model_id}.json"
            with open(target_path, "w", encoding="utf-8") as f:
                json.dump(record_data, f, indent=2)
            logger.warning(">>> [PROMOTION REJECTED] %s failed filters: %s -> QUARANTINED in research/candidates/failed/", model_id, "; ".join(reasons))

        return verdict

    @classmethod
    def _register_champion(cls, model_id: str, data: Dict[str, Any]):
        """Persists certified champion into crypto_engine's registry."""
        champions = {}
        if REGISTRY_FILE.exists():
            try:
                with open(REGISTRY_FILE, "r", encoding="utf-8") as f:
                    champions = json.load(f)
            except Exception:
                champions = {}

        champions[model_id] = data
        with open(REGISTRY_FILE, "w", encoding="utf-8") as f:
            json.dump(champions, f, indent=2)

    @classmethod
    def list_live_champions(cls) -> Dict[str, Any]:
        """Lists active certified production champions."""
        if REGISTRY_FILE.exists():
            try:
                with open(REGISTRY_FILE, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception:
                pass
        return {}
